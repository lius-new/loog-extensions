    #[test]
    fn the_agent_is_inflated_in_bounded_pieces_without_loss_and_ends_empty() {
        let data: Vec<u8> = (0..UPLOAD_CHUNK * 3 + 5).map(|n| ((n * n) % 251) as u8).collect();
        let packed: &'static [u8] = Box::leak(miniz_oxide::deflate::compress_to_vec(&data, 6).into_boxed_slice());
        assert!(packed.len() < data.len(), "the test data must be compressible");
        let agent = Agent { machine: "x86_64", sha256: "ab", size: data.len(), bytes: packed };
        let (mut inflater, mut piece, mut all) = (Inflater::new(&agent), Vec::new(), Vec::new());
        loop {
            inflater.next(&mut piece).unwrap();
            if piece.is_empty() { break; }
            assert!(piece.len() <= UPLOAD_CHUNK);
            all.extend_from_slice(&piece);
        }
        assert_eq!(all, data);
        inflater.next(&mut piece).unwrap();
        assert!(piece.is_empty(), "after the end there is nothing more, and no error");
    }
    #[test]
    fn an_agent_that_is_damaged_cut_short_or_not_its_stated_size_is_an_error() {
        let data: Vec<u8> = (0..UPLOAD_CHUNK + 100).map(|n| (n % 97) as u8).collect();
        let packed: &'static [u8] = Box::leak(miniz_oxide::deflate::compress_to_vec(&data, 6).into_boxed_slice());
        let drain = |size: usize, bytes: &'static [u8]| {
            let (mut inflater, mut piece) = (Inflater::new(&Agent { machine: "x86_64", sha256: "ab", size, bytes }), Vec::new());
            loop {
                inflater.next(&mut piece)?;
                if piece.is_empty() { return Ok::<(), String>(()); }
            }
        };
        assert!(drain(data.len(), packed).is_ok());
        assert!(drain(data.len() + 1, packed).is_err(), "more was promised to the target than there is");
        assert!(drain(data.len() - 1, packed).is_err(), "less was promised to the target than there is");
        assert!(drain(data.len(), &packed[..packed.len() / 2]).is_err(), "a stream that ends early");
        assert!(drain(data.len(), Box::leak(vec![0xff; 64].into_boxed_slice())).is_err(), "bytes that are not a stream");
    }
